test('booking, occupied slots and rescheduling use the actual availability picker', async ({ page }, info) => {
  test.setTimeout(60000)
  const { patient } = await setup(page, info, 'حجز موعد')
  const date = { desktop: '2026-11-02', tablet: '2026-11-03', mobile: '2026-11-04' }[info.project.name]
  await page.goto(`/appointments/new?patientId=${patient.id}&date=${date}`)
  const doctor = page.getByRole('combobox', { name: 'الطبيب', exact: true })
  const doctorId = await doctor.locator('option').filter({ hasText: 'Synthetic doctor' }).getAttribute('value')
  await doctor.selectOption(doctorId)
  const time = page.getByRole('combobox', { name: 'وقت الموعد', exact: true })
  await expect(time).toBeEnabled()
  await time.selectOption('10:00')
  await page.getByRole('textbox', { name: 'ملاحظات', exact: true }).fill('Synthetic booking')
  const pending = page.waitForResponse(r => r.url().endsWith('/appointments/') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'حفظ الموعد', exact: true }).click()
  const created = await pending
  expect(created.status()).toBe(201)
  const appointment = (await created.json()).data
  await expect(page).toHaveURL(/\/appointments$/)
  await page.goto(`/appointments/new?patientId=${patient.id}&date=${date}`)
  await doctor.selectOption(doctorId)
  await expect(time.locator('option[value="10:00"]')).toBeDisabled()
  await page.goto(`/appointments/${appointment.id}/edit`)
  await expect(time).toBeEnabled()
  await expect(time).toHaveValue('10:00')
  await expect(time.locator('option[value="10:00"]')).toBeEnabled()
  await time.selectOption('10:30')
  await page.getByRole('button', { name: 'حفظ الموعد', exact: true }).click()
  await expect(page).toHaveURL(/\/appointments$/)
  const updated = await page.request.get(`/api/v1/appointments/${appointment.id}/`)
  const state = (await updated.json()).data
  expect(state.appointment_time).toBe('10:30:00')
  expect(state.appointment_date).toBe(date)
  expect(state.version).toBe(2)
  await page.reload()
  await expect(page.locator('#main-content')).toBeVisible()
})

