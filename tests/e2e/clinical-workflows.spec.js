test('invoice form computes fractional totals, issues, pays and exports the paid snapshot', async ({ page }, info) => {
  const { patient, headers } = await setup(page, info, 'فاتورة مدفوعة')
  await page.goto('/invoices/new')
  await page.getByRole('combobox', { name: 'المريض', exact: true }).selectOption(String(patient.id))
  await page.getByRole('spinbutton', { name: 'المبلغ الإجمالي', exact: true }).fill('10.75')
  await page.getByRole('spinbutton', { name: 'الضريبة', exact: true }).fill('0.25')
  await page.getByRole('spinbutton', { name: 'الخصم', exact: true }).fill('1.50')
  await expect(page.getByRole('spinbutton', { name: 'المبلغ النهائي (محسوب تلقائياً)', exact: true })).toHaveValue('9.5')
  await page.getByRole('combobox', { name: 'طريقة الدفع', exact: true }).selectOption('card')
  expect(await page.locator('form').evaluate(form => [...form.elements].filter(el => el.checkValidity && !el.checkValidity()).map(el => ({ id: el.id, type: el.type, value: el.value, step: el.step, message: el.validationMessage })))).toEqual([])
  const pending = page.waitForResponse(r => r.url().endsWith('/billing/') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'حفظ الفاتورة', exact: true }).click()
  const created = await pending
  expect(created.status()).toBe(201)
  const invoice = (await created.json()).data
  await expect(page).toHaveURL(/\/invoices$/)
  const row = page.locator('tr').filter({ hasText: invoice.invoice_number })
  await row.getByRole('button', { name: 'إصدار', exact: true }).click()
  await confirm(page)
  await expect(row.getByRole('button', { name: 'دفع', exact: true })).toBeVisible()
  await row.getByRole('button', { name: 'دفع', exact: true }).click()
  await confirm(page)
  await expect(row.getByRole('button', { name: 'دفع', exact: true })).toHaveCount(0)
  const state = (await (await page.request.get(`/api/v1/billing/${invoice.id}/`)).json()).data
  expect(state.status).toBe('paid')
  expect(state.final_amount).toBe('9.50')
  expect(state.payment_method).toBe('card')
  await expect(row).toContainText('SYP')
  expect(state.paid_at).toBeTruthy()
  expect(state.paid_by).toBeTruthy()
  const rejected = await page.request.patch(`/api/v1/billing/${invoice.id}/`, {
    data: { total_amount: '99.00', version: state.version }, headers: await headers(),
  })
  expect(rejected.status()).toBe(400)
  await downloaded(page, info, 'invoice.pdf', () => row.getByRole('button', { name: 'تنزيل PDF', exact: true }).click())
  await page.reload()
  await expect(page.locator('tr').filter({ hasText: invoice.invoice_number })).toContainText('مدفوعة')
})

test('patient import wizard previews, assigns care team and commits unknown/year-only birth', async ({ page }, info) => {
  await setup(page, info, 'قبل الاستيراد')
  await page.goto('/import')
  const doctor = page.getByRole('combobox', { name: 'الطبيب المسؤول', exact: true })
  const id = await doctor.locator('option').filter({ hasText: 'Synthetic doctor' }).getAttribute('value')
  await doctor.selectOption(id)
  const surname = `وارد جديد ${info.project.name}`
  const csv = `الاسم الأول,اللقب,الرقم الوطني,سنة الميلاد\nأول,${surname},,\nثان,${surname},,1990\n,ناقص,,\n`
  await page.locator('input[type=file]').setInputFiles({ name: 'synthetic-patients.csv', mimeType: 'text/csv', buffer: Buffer.from('\uFEFF' + csv) })
  await expect(page.getByRole('button', { name: 'التالي', exact: true })).toBeEnabled()
  const before = await page.request.get(`/api/v1/patients/?search=${encodeURIComponent(surname)}`)
  expect(items(await before.json())).toHaveLength(0)
  await page.getByRole('button', { name: 'التالي', exact: true }).click()
  await expect(page.getByText('سيتم استيراد 2 مريض')).toBeVisible()
  await page.getByRole('button', { name: 'تأكيد الاستيراد', exact: true }).click()
  await expect(page.getByText('تم الاستيراد', { exact: true })).toBeVisible()
  const patients = items(await (await page.request.get(`/api/v1/patients/?search=${encodeURIComponent(surname)}`)).json())
  expect(patients).toHaveLength(2)
  expect(patients.find(row => row.first_name === 'أول').dob_year).toBeNull()
  expect(patients.find(row => row.first_name === 'ثان').dob_year).toBe(1990)
  for (const patient of patients) {
    const team = (await (await page.request.get(`/api/v1/patients/${patient.id}/care_team/`)).json()).data.care_team
    expect(team.some(member => member.user === Number(id) && !member.ended_at)).toBe(true)
  }
  await page.getByRole('link', { name: 'عرض المرضى', exact: true }).click()
  await expect(page).toHaveURL(/\/patients$/)
})

test('medication import maps all five columns and requires preview before execution', async ({ page }, info) => {
  await setup(page, info, 'قبل استيراد دواء')
  await page.goto('/import/options')
  const name = `Synthetic Workflow ${info.project.name}`
  await page.locator('#medFile').setInputFiles({ name: 'synthetic-medications.csv', mimeType: 'text/csv',
    buffer: Buffer.from(`english,arabic,dose,brand_en,brand_ar\n${name},دواء اصطناعي,10 mg,SuiteBrand,علامة اصطناعية\n`) })
  await page.getByRole('button', { name: 'رفع وتحديد الأعمدة', exact: true }).click()
  for (const [selector, value] of [['#mapGenericEnglish', '0'], ['#mapGenericArabic', '1'], ['#mapDosage', '2'], ['#mapBrandEnglish', '3'], ['#mapBrandArabic', '4']]) {
    await page.locator(selector).selectOption(value)
  }
  await page.getByRole('button', { name: 'معاينة الاستيراد', exact: true }).click()
  await expect(page.getByRole('button', { name: 'تأكيد استيراد الأدوية', exact: true })).toBeVisible()
  expect(items(await (await page.request.get(`/api/v1/options/medications/?search=${encodeURIComponent(name)}`, { maxRetries: 2 })).json())).toHaveLength(0)
  await page.getByRole('button', { name: 'تأكيد استيراد الأدوية', exact: true }).click()
  await expect(page.locator('#mapGenericEnglish')).toHaveCount(0)
  const medications = items(await (await page.request.get(`/api/v1/options/medications/?search=${encodeURIComponent(name)}`, { maxRetries: 2 })).json())
  expect(medications).toHaveLength(1)
  expect(medications[0].generic_english).toBe(name)
  expect(medications[0].generic_arabic).toBe('دواء اصطناعي')
  expect(medications[0].dosage).toBe('10 mg')
})


test('draft visit archive uses one checkbox confirmation and the displayed opening version', async ({ page }, info) => {
  const { patient, headers } = await setup(page, info, 'أرشفة اصطناعية')
  const response = await page.request.post(`/api/v1/patients/${patient.id}/visits/`, {
    headers: await headers(), data: { visit_date: '2026-10-12', main_complaints: 'Synthetic archive complaint' },
  })
  expect(response.status()).toBe(201)
  const visit = (await response.json()).data
  let writes = 0
  page.on('request', request => { if (request.method() === 'DELETE' && request.url().endsWith(`/visits/${visit.id}/`)) writes++ })
  await page.goto('/visits')
  const row = page.locator('tbody tr').filter({ hasText: patient.surname })
  await expect(row).toBeVisible()
  await row.getByTitle('أرشفة المسودة', { exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'إلغاء', exact: true }).click()
  expect(writes).toBe(0)
  await row.getByTitle('أرشفة المسودة', { exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: 'نعم', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  const pending = page.waitForResponse(value => value.request().method() === 'DELETE' && value.url().endsWith(`/visits/${visit.id}/`))
  await dialog.getByRole('button', { name: 'نعم', exact: true }).click()
  const archived = await pending
  expect(archived.status()).toBe(204)
  expect(archived.request().postDataJSON()).toEqual({ version: visit.version })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(row).toHaveCount(0)
  expect(writes).toBe(1)
})
