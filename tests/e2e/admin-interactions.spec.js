test('user create validation, edit without password change and confirmed disable refresh the list', async ({ page }, info) => {
  await login(page)
  const username = `interaction_${info.project.name}`
  await page.goto('/users/new')
  await page.getByRole('textbox', { name: 'اسم المستخدم', exact: true }).fill(username)
  await page.getByRole('textbox', { name: 'الاسم الكامل', exact: true }).fill('Synthetic interaction user')
  await page.getByLabel(/^كلمة المرور\s*\*?$/).fill(password)
  await page.getByLabel(/^تأكيد كلمة المرور\s*\*?$/).fill('Different-Pass!42')
  await page.getByRole('button', { name: 'حفظ', exact: true }).click()
  await expect(page.locator('form').getByText('كلمتا المرور غير متطابقتين', { exact: true })).toBeVisible()
  await page.getByLabel(/^تأكيد كلمة المرور\s*\*?$/).fill(password)
  await page.getByRole('button', { name: 'حفظ', exact: true }).click()
  await expect(page).toHaveURL(/\/users$/)
  const row = page.getByRole('row').filter({ hasText: username })
  await row.locator('[title="تعديل"]').click()
  await expect(page.getByLabel('كلمة المرور الجديدة (اختياري)')).toHaveValue('')
  await page.getByRole('textbox', { name: 'الاسم الكامل', exact: true }).fill('Synthetic revised user')
  const updated = page.waitForResponse(response => /\/auth\/users\/\d+\/$/.test(response.url()) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'حفظ', exact: true }).click()
  const response = await updated
  expect(response.ok()).toBe(true)
  expect(response.request().postDataJSON().password).toBeUndefined()
  await expect(page).toHaveURL(/\/users$/)
  await expect(row).toContainText('Synthetic revised user')
  await row.locator('[title="حذف"]').click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'نعم', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.reload()
  await expect(row).toHaveCount(0)
})

test('patient demographic edit preserves identifiers and clinical unknowns after reload', async ({ page }, info) => {
  const { patient } = await setup(page, info, 'تعديل تفاعل')
  await page.goto(`/patients/${patient.id}/edit`)
  await page.getByRole('textbox', { name: 'المهنة الحالية', exact: true }).fill('Synthetic interaction occupation')
  await page.getByRole('textbox', { name: 'سبب تصحيح بيانات الملف', exact: true }).fill('Synthetic interaction correction')
  await page.getByRole('button', { name: 'تحديث السجل الطبي', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/patients/${patient.id}$`))
  await page.reload()
  const response = await page.request.get(`/api/v1/patients/${patient.id}/`)
  const saved = (await response.json()).data
  expect(saved.id).toBe(patient.id)
  expect(saved.occupation).toBe('Synthetic interaction occupation')
  expect(saved.gender).toBe(patient.gender)
  expect(saved.dob_year).toBe(patient.dob_year)
  expect(saved.allergy_status).toBe('unknown')
  expect(saved.version).toBeGreaterThan(patient.version)
})
