import { test, expect } from '@playwright/test'
import { login, password, setup } from './helpers/workflow.js'

async function retireAndRestore(page, row) {
  await row.locator('[title="حذف"]').click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: 'نعم', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'إلغاء', exact: true }).click()
  await expect(row.locator('[title="تعديل"]')).toBeVisible()
  await row.locator('[title="حذف"]').click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'نعم', exact: true }).click()
  await expect(row.locator('[title="تعديل"]')).toHaveCount(0)
  await row.locator('[title="إعادة التفعيل"]').click()
  await expect(row.locator('[title="تعديل"]')).toBeVisible()
}

for (const spec of [
  { route: 'diagnoses', add: 'إضافة تشخيص جديد', input: '#diagEnglish', base: '/options/diagnoses/' },
  { route: 'medications', add: 'إضافة دواء جديد', input: '#medGenericEnglish', base: '/options/medications/' },
]) {
  test(`${spec.route} create, versioned edit, cancel retirement and reactivate through the real UI`, async ({ page }, info) => {
    await login(page)
    const name = `Synthetic ${spec.route} ${info.project.name}`
    await page.goto(`/${spec.route}`)
    await page.getByRole('button', { name: spec.add }).click()
    const dialog = page.getByRole('dialog')
    await dialog.locator(spec.input).fill(name)
    if (spec.route === 'diagnoses') {
      await dialog.locator('#diagCode').fill(`SYN.${info.project.name}`)
      await dialog.locator('#diagArabic').fill('تشخيص اصطناعي')
    } else await dialog.locator('#medDosage').fill('10 mg')
    const created = page.waitForResponse(response => response.url().endsWith(spec.base) && response.request().method() === 'POST')
    await dialog.getByRole('button', { name: 'حفظ', exact: true }).click()
    expect((await created).status()).toBe(201)
    await expect(dialog).toHaveCount(0)
    const row = page.getByRole('row').filter({ hasText: name })
    await row.locator('[title="تعديل"]').click()
    await expect(dialog.locator(spec.input)).toHaveValue(name)
    await dialog.locator(spec.input).fill(`${name} revised`)
    const updated = page.waitForResponse(response => response.url().includes(spec.base) && response.request().method() === 'PUT')
    await dialog.getByRole('button', { name: 'حفظ', exact: true }).click()
    const response = await updated
    expect(response.status()).toBe(200)
    expect(response.request().postDataJSON().version).toBeGreaterThan(0)
    await expect(dialog).toHaveCount(0)
    await expect(row).toContainText(`${name} revised`)
    await retireAndRestore(page, row)
    await page.reload()
    await expect(row.locator('[title="تعديل"]')).toBeVisible()
  })
}

